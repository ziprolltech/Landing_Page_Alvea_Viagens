'use client'

import { useState, useEffect, useMemo, useRef } from 'react'
import { createPortal } from 'react-dom'
import { motion, AnimatePresence } from 'framer-motion'
import { Search, MapPin } from 'lucide-react'
import Fuse from 'fuse.js'
import { AIRPORTS, type Airport } from '@/data/airports'

/* ── Shared input style ─────────────────────────────────────────────────── */

const INPUT_CLASS = [
  'w-full bg-white/[0.06] border border-white/[0.12]',
  'rounded-xl px-4 py-3.5 text-white placeholder-white/30',
  'focus:outline-none focus:border-gold/40 focus:bg-white/[0.09]',
  'transition-all duration-200 text-[15px]',
].join(' ')

/* ── Props ──────────────────────────────────────────────────────────────── */

interface AirportAutocompleteProps {
  value:    string
  onChange: (value: string) => void
}

/* ── Normalizer — explicit Unicode escape, encoding-safe ───────────────── */

function norm(s: string): string {
  return s.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '')
}

/* ── The airport base ─────────────────────────────────────────────────────────
   Complete base: src/data/airports-world.json — about 8,500 open airports with
   an IATA code, worldwide (generated by scripts/build-airports.mjs from
   OurAirports; see that file for what is in it and how it is cleaned).

   It is a separate chunk, fetched once from this site when the autocomplete
   first mounts — not part of the page's own JavaScript, and never a request
   per search. Until it arrives, the search answers from the small hand-written
   list (src/data/airports.ts), so the field works from the first keystroke.

   Each airport gets pre-normalized shadow fields, so every keystroke is plain
   string comparisons over the list (well under a millisecond per thousand
   airports), accent-insensitive:
     _nc code · _ns city · _na airport name · _nb name without "Aeroporto …"
     _nk country · _al aliases (city code such as "lon", and the city as the
     source spells it, e.g. "london" for Londres)
────────────────────────────────────────────────────────────────────────── */

type SearchEntry = Airport & {
  _nc: string
  _ns: string
  _na: string
  _nb: string
  _nk: string
  _al: string[]
}

function toEntry(a: Airport, alias = ''): SearchEntry {
  const name = norm(a.airport)
  return {
    ...a,
    _nc: norm(a.code),
    _ns: norm(a.city),
    _na: name,
    _nb: name.replace(/^aeroporto (internacional |regional |municipal )?(de |do |da |dos |das )?/, ''),
    _nk: norm(a.country),
    _al: alias ? alias.split(' ') : [],
  }
}

let SEARCH_DATA: SearchEntry[] = AIRPORTS.map(a => toEntry(a))

/* Fuse is kept for typo-tolerance on queries that produce ZERO direct hits
   (e.g. "londre" → Londres, "guarulos" → Guarulhos). It is NOT used when
   direct/prefix matches already exist, and its index is only built the first
   time it is needed. */
let fuse: Fuse<SearchEntry> | null = null

function fuzzy(): Fuse<SearchEntry> {
  fuse ??= new Fuse<SearchEntry>(SEARCH_DATA, {
    keys: [
      { name: '_nc', weight: 4 },
      { name: '_ns', weight: 2 },
      { name: '_nb', weight: 1 },
    ],
    threshold:          0.25,
    minMatchCharLength: 2,
    ignoreLocation:     true,
    shouldSort:         true,
    useExtendedSearch:  false,
  })
  return fuse
}

type WorldBase = {
  countries: string[]
  /* [iata, name, city, country index, icao, aliases] — ordered by importance */
  airports:  [string, string, string, number, string, string][]
}

let worldLoading: Promise<void> | null = null

function loadWorldBase(): Promise<void> {
  worldLoading ??= import('@/data/airports-world.json')
    .then(module => {
      const world = module.default as unknown as WorldBase
      SEARCH_DATA = world.airports.map(([code, airport, city, country, icao, alias]) =>
        toEntry({ code, airport, city, country: world.countries[country], ...(icao ? { icao } : {}) }, alias))
      fuse = null
    })
    .catch(() => { worldLoading = null })   // keep the small list; try again next time
  return worldLoading
}

/* ── Tiered search ───────────────────────────────────────────────────────────
   Priority order (lower score = higher priority):
     0  exact IATA code               "gru"   → GRU
     1  IATA code startsWith          "gr"    → GRU, GRO…
        city code                     "lon"   → LHR, LGW, STN…  "par" → CDG, ORY
     2  city startsWith               "rio"   → GIG, SDU
     3  airport name startsWith       "guar"  → GRU   (ignoring "Aeroporto …")
        city, as the source spells it "london" → Londres
     4  city contains                 "de janeiro"
     5  airport name contains         "kennedy"
     6  country startsWith            "portugal" → LIS, OPO, FAO…
     7  country contains
     10+ Fuse fuzzy fallback          ONLY when the tiers above produce nothing

   Each airport is added at its BEST tier only. Within a tier the order is the
   order of the base, which is by importance (busiest airports first), so
   "são paulo" lists GRU before the smaller fields. Only the top MAX_RESULTS
   are shown, however large the base is.
───────────────────────────────────────────────────────────────────────────── */

const MAX_RESULTS = 8

function searchAirports(query: string): Airport[] {
  const q = norm(query.trim())
  if (q.length < 2) return []

  interface Ranked { airport: Airport; score: number }
  const seen   = new Set<string>()
  const ranked: Ranked[] = []

  function push(entry: SearchEntry, score: number) {
    if (seen.has(entry.code)) return
    seen.add(entry.code)
    ranked.push({
      airport: {
        code: entry.code, airport: entry.airport, city: entry.city, country: entry.country,
        ...(entry.icao ? { icao: entry.icao } : {}),
      },
      score,
    })
  }

  for (const e of SEARCH_DATA) {
    if (e._nc === q)                           { push(e, 0); continue }
    if (e._nc.startsWith(q))                   { push(e, 1); continue }
    if (e._al.includes(q))                     { push(e, 1); continue }
    if (e._ns.startsWith(q))                   { push(e, 2); continue }
    if (e._nb.startsWith(q))                   { push(e, 3); continue }
    if (e._al.some(word => word.startsWith(q))) { push(e, 3); continue }
    if (e._ns.includes(q))                     { push(e, 4); continue }
    if (e._na.includes(q))                     { push(e, 5); continue }
    if (e._nk.startsWith(q))                   { push(e, 6); continue }
    if (e._nk.includes(q))                     { push(e, 7) }
  }

  /* Only run Fuse when the tiers produced nothing (catches typos) */
  if (ranked.length === 0) {
    fuzzy().search(q, { limit: MAX_RESULTS }).forEach((hit, i) => push(hit.item, 10 + i))
  }

  return ranked
    .sort((a, b) => a.score - b.score)
    .slice(0, MAX_RESULTS)
    .map(r => r.airport)
}

/* ── Component ──────────────────────────────────────────────────────────── */
/*
 * Fully local — no external requests, no debounce, no loading state.
 * The search runs in the browser against the airport base (see above).
 *
 * AnimatePresence lives INSIDE the portal, not outside it.
 * Wrapping a portal from outside means Framer Motion cannot track the
 * motion.div key for exit animations. Moving it inside fixes that.
 *
 * Dropdown portal renders to document.body with position:fixed so it
 * escapes the modal's overflow-hidden / overflow-y-auto clipping context.
 *
 * Selection uses onMouseDown + e.preventDefault() so the suggestion fires
 * before the global mousedown-outside handler closes the dropdown.
 *
 * skipSyncRef: when the user edits after a prior selection, we call
 * onChange('') to invalidate it. The parent passes value='' back as a prop,
 * which would normally reset the input via the useEffect. The ref skips
 * exactly that one sync so the user's typed characters are preserved.
 */

export default function AirportAutocomplete({ value, onChange }: AirportAutocompleteProps) {
  const [query,     setQuery]     = useState(value)
  const [open,      setOpen]      = useState(false)
  const [inputRect, setInputRect] = useState<DOMRect | null>(null)

  const inputRef    = useRef<HTMLInputElement>(null)
  const skipSyncRef = useRef(false)

  /* The complete base arrives once, shortly after the field appears */
  const [base, setBase] = useState(0)
  useEffect(() => {
    let alive = true
    loadWorldBase().then(() => { if (alive) setBase(n => n + 1) })
    return () => { alive = false }
  }, [])

  /* Instant results — recomputed whenever the query (or the base) changes */
  // eslint-disable-next-line react-hooks/exhaustive-deps -- `base` only signals that the module-level list was replaced
  const results = useMemo(() => searchAirports(query), [query, base])

  /* Sync if parent resets value (modal close, step navigation) */
  useEffect(() => {
    if (skipSyncRef.current) { skipSyncRef.current = false; return }
    setQuery(value)
  }, [value])

  /* Close when clicking outside the input */
  useEffect(() => {
    function onOutside(e: MouseEvent) {
      if (!inputRef.current?.contains(e.target as Node)) setOpen(false)
    }
    document.addEventListener('mousedown', onOutside)
    return () => document.removeEventListener('mousedown', onOutside)
  }, [])

  function snapRect() {
    if (inputRef.current) setInputRect(inputRef.current.getBoundingClientRect())
  }

  function handleChange(e: React.ChangeEvent<HTMLInputElement>) {
    const v = e.target.value
    setQuery(v)
    if (value !== '') {
      /* Invalidate prior selection; skip the resulting value='' prop update */
      skipSyncRef.current = true
      onChange('')
    }
    if (!v) { setOpen(false); return }
    snapRect()
    setOpen(true)
  }

  function select(airport: Airport) {
    const label = `${airport.city} (${airport.code})`
    setQuery(label)
    onChange(label)
    setOpen(false)
  }

  const showDropdown = open && results.length > 0 && inputRect !== null

  /* ── SSR guard: portals require document ── */
  const [mounted, setMounted] = useState(false)
  useEffect(() => { setMounted(true) }, [])

  return (
    <>
      {/* ── Input ── */}
      <div className="relative">
        <input
          ref={inputRef}
          type="text"
          value={query}
          onChange={handleChange}
          onFocus={() => {
            if (!value && results.length > 0) { snapRect(); setOpen(true) }
          }}
          placeholder="Ex: São Paulo, Rio de Janeiro, Brasília…"
          className={`${INPUT_CLASS} pr-11`}
          autoComplete="off"
          spellCheck={false}
        />
        <div className="absolute right-4 top-1/2 -translate-y-1/2 pointer-events-none">
          {value
            ? <MapPin size={15} style={{ color: '#D4A853' }} />
            : <Search size={15} style={{ color: 'rgba(212,168,83,0.42)' }} />
          }
        </div>
      </div>

      {/* ── Portal dropdown ─────────────────────────────────────────────────
          AnimatePresence lives INSIDE the portal so Framer Motion can track
          the motion.div key directly — not through a portal wrapper node.
          position:fixed + getBoundingClientRect() escapes the modal's
          overflow-hidden / overflow-y-auto clipping context.
      ─────────────────────────────────────────────────────────────────── */}
      {mounted && showDropdown && inputRect && createPortal(
        <AnimatePresence>
          <motion.div
            key="airport-dropdown"
            initial={{ opacity: 0, y: -8, scale: 0.97 }}
            animate={{ opacity: 1, y: 0,  scale: 1    }}
            exit={{    opacity: 0, y: -8, scale: 0.97 }}
            transition={{ duration: 0.18, ease: [0.22, 1, 0.36, 1] }}
            style={{
              position:             'fixed',
              top:                  inputRect.bottom + 8,
              left:                 inputRect.left,
              width:                inputRect.width,
              zIndex:               10001,
              background:           'rgba(7,16,36,0.98)',
              backdropFilter:       'blur(32px)',
              WebkitBackdropFilter: 'blur(32px)',
              border:               '1px solid rgba(212,168,83,0.22)',
              boxShadow:            '0 28px 72px rgba(0,0,0,0.75), 0 0 0 1px rgba(212,168,83,0.06) inset',
              borderRadius:         '16px',
              overflow:             'hidden',
            }}
          >
            {results.map((airport, i) => (
              <motion.button
                key={airport.code}
                type="button"
                className="w-full text-left px-4 py-3.5 flex items-center gap-3.5"
                style={{
                  borderBottom: i < results.length - 1
                    ? '1px solid rgba(255,255,255,0.05)'
                    : 'none',
                }}
                initial={{ backgroundColor: 'rgba(0,0,0,0)' }}
                whileHover={{ backgroundColor: 'rgba(212,168,83,0.10)' }}
                transition={{ duration: 0.10 }}
                onMouseDown={e => { e.preventDefault(); select(airport) }}
              >
                {/* IATA badge */}
                <div
                  className="w-10 h-8 rounded-lg flex items-center justify-center shrink-0 text-[10px] font-black tracking-wider"
                  style={{ background: 'rgba(212,168,83,0.14)', color: '#D4A853' }}
                >
                  {airport.code}
                </div>

                {/* Airport info */}
                <div className="flex-1 min-w-0">
                  <p className="text-white text-[13.5px] font-semibold leading-tight truncate">
                    {airport.airport}
                  </p>
                  <p className="text-white/40 text-[11px] leading-tight mt-[3px] truncate">
                    {airport.city} • {airport.country}
                  </p>
                </div>
              </motion.button>
            ))}
          </motion.div>
        </AnimatePresence>,
        document.body
      )}
    </>
  )
}
